#!/usr/bin/env python3
"""Generates src/tokens.generated.ts and src/styles/tokens.generated.css from design/work/common.py.

Run from anywhere: python3 packages/pwa/scripts/gen-tokens.py [--check]
--check exits 1 if the committed files differ (used by the token test and CI).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PWA = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(PWA, '..', '..', 'design', 'work'))
import common  # noqa: E402


def build():
    states = {}
    for code, (label, text, hue, fill, ink, glyph, mute) in common.STATES.items():
        mute = mute or hue
        states[code] = dict(
            label=label, text=text, hue=hue, fill=fill, ink=ink, glyph=glyph, mute=mute,
            hb=f'{hue}50',
            cf=common.mix(hue, 0x0e / 255), cb=common.mix(hue, 0x38 / 255),
            cfs=common.mix(hue, 0x0e / 255, common.SURFACE['selectedCard']),
            cfh=common.mix(hue, 0x0e / 255, common.DOCK['hover']),
        )
    return dict(T=common.T, DOCK=common.DOCK, SURFACE=common.SURFACE, STATES=states,
                GLYPHS=common.GLYPHS, ICON=common.ICON, ICON_STROKE=common.WIDTH)


def ts(data):
    out = ['// GENERATED by scripts/gen-tokens.py from design/work/common.py. Do not edit.',
           '// Regenerate with: pnpm --filter @herdr-remote/pwa tokens', '']
    for k, v in data.items():
        out.append(f'export const {k} = {json.dumps(v, indent=2, ensure_ascii=False)} as const;\n')
    out.append('export type StateCode = keyof typeof STATES;\n')
    return '\n'.join(out)


GLYPH_DIR = os.path.join(PWA, 'src', 'assets', 'glyphs')


def svg_file(glyph, color):
    return common.GLYPHS[glyph].replace('"C"', '"' + color + '"') + '\n'


def glyph_files(data):
    """Glyphs are emitted as files, not data: URIs, so the planned CSP (default-src 'self') allows them."""
    out = {os.path.join(GLYPH_DIR, 'spinner-working.svg'): svg_file('spinner', common.T['working'])}
    for code, (label, text, hue, fill, ink, glyph, mute) in common.STATES.items():
        if glyph:
            m = data['STATES'][code]['mute']
            out[os.path.join(GLYPH_DIR, f'{code}-gi.svg')] = svg_file(glyph, ink)
            out[os.path.join(GLYPH_DIR, f'{code}-gm.svg')] = svg_file(glyph, m)
    return out


def css(data):
    out = ['/* GENERATED by scripts/gen-tokens.py from design/work/common.py. Do not edit. */', ':root{']
    for k, v in data['T'].items():
        out.append(f'  --t-{k.replace("_", "-")}:{v};')
    for k, v in data['DOCK'].items():
        out.append(f'  --dock-{k}:{v};')
    for k, v in data['SURFACE'].items():
        out.append(f'  --surface-{k}:{v};')
    out.append('  --spinner-working:url("../assets/glyphs/spinner-working.svg");')
    out.append('}')
    for code, (label, text, hue, fill, ink, glyph, mute) in common.STATES.items():
        s = data['STATES'][code]
        v = [f'--hue:{s["hue"]}', f'--fill:{s["fill"]}', f'--ink:{s["ink"]}', f'--hb:{s["hb"]}',
             f'--cf:{s["cf"]}', f'--cb:{s["cb"]}', f'--cfs:{s["cfs"]}', f'--cfh:{s["cfh"]}', f'--mute:{s["mute"]}']
        if glyph:
            v += [f'--gi:url("../assets/glyphs/{code}-gi.svg")', f'--gm:url("../assets/glyphs/{code}-gm.svg")']
        else:
            v += ['--gi:none', '--gm:none']
        out.append(f'.s-{code}{{{";".join(v)}}}')
    return '\n'.join(out) + '\n'


def main():
    data = build()
    files = {
        os.path.join(PWA, 'src', 'tokens.generated.ts'): ts(data),
        os.path.join(PWA, 'src', 'styles', 'tokens.generated.css'): css(data),
        **glyph_files(data),
    }
    os.makedirs(GLYPH_DIR, exist_ok=True)
    stale = set(os.listdir(GLYPH_DIR)) - {os.path.basename(p) for p in files}
    if stale and '--check' in sys.argv:
        print('stale glyph files:', sorted(stale))
        sys.exit(1)
    for name in stale:
        os.remove(os.path.join(GLYPH_DIR, name))
    bad = 0
    for path, text in files.items():
        if '--check' in sys.argv:
            if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
                print('stale:', path)
                bad = 1
        else:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
    sys.exit(bad)


main()
