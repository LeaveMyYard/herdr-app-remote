// Self-contained ESM files for the installer (no node_modules at run time): dist/bridge.mjs, and
// dist/claude-reader.mjs, the chat view's reader child (src/claude/reader-child.ts with the pinned Claude
// Agent SDK). The reader is built first: its sha256 goes into bridge.mjs, which runs no other reader.
// Deterministic: same sources, same bytes, so the hashes in install.json are reproducible.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { build } from "esbuild";
import { fileURLToPath, URL } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

// The reader child: only the SDK's session readers are imported; the SDK's own bundle needs only node built-ins.
await build({
  entryPoints: [here("../src/claude/reader-child.ts")],
  outfile: here("../dist/claude-reader.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: false,
  sourcemap: false,
  legalComments: "eof",
  // The SDK's notice is a plain comment, which esbuild drops: keep it at the top (THIRD-PARTY.md).
  banner: {
    js: [
      "// herdr-app-remote Claude reader child. Generated by packages/bridge/scripts/bundle.mjs; do not edit.",
      "// Includes @anthropic-ai/claude-agent-sdk (pinned in packages/bridge/package.json):",
      "// (c) Anthropic PBC. All rights reserved. Use is subject to the Legal Agreements outlined here: https://code.claude.com/docs/en/legal-and-compliance.",
    ].join("\n"),
  },
  logLevel: "warning",
});

const readerSha256 = createHash("sha256").update(readFileSync(here("../dist/claude-reader.mjs"))).digest("hex");

await build({
  entryPoints: [here("../src/daemon/cli.ts")],
  outfile: here("../dist/bridge.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: false,
  sourcemap: false,
  legalComments: "eof",
  // ws is CommonJS: its require() calls of node built-ins need a real require in an ESM bundle.
  banner: {
    js: [
      "// herdr-app-remote bridge. Generated by packages/bridge/scripts/bundle.mjs; do not edit.",
      'import { createRequire as __herdrRemoteCreateRequire } from "node:module";',
      "const require = __herdrRemoteCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  // ws's optional native speed-ups: absent is fine, ws falls back to JS.
  external: ["bufferutil", "utf-8-validate"],
  // The reader built just above: the bridge runs only a claude-reader.mjs with this hash (src/claude/build-info.ts).
  define: { __HERDR_READER_SHA256__: JSON.stringify(readerSha256) },
  logLevel: "warning",
});

