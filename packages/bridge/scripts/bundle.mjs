// One self-contained ESM file for the installer: dist/bridge.mjs (no node_modules at run time).
// Deterministic: same sources, same bytes, so the hash in install.json is reproducible.
import { build } from "esbuild";
import { fileURLToPath, URL } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

await build({
  entryPoints: [here("../src/daemon/cli.ts")],
  outfile: here("../dist/bridge.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: false,
  sourcemap: false,
  legalComments: "eof",
  banner: { js: "// herdr-app-remote bridge. Generated by packages/bridge/scripts/bundle.mjs; do not edit." },
  logLevel: "warning",
});
